/**
 * 본문 안의 강조와 줄머리 꼬리표.
 *
 * 교재 글에는 두 가지 표시가 필요하다.
 *   ① **별표 두 개**로 감싼 강조 — 강사가 짚는 대목
 *   ② 줄머리의 꼬리표 — 「제목」·「방법」·「결과」, 대본의 화자 이름
 *
 * ②를 본문 활자 그대로 두면 「제목 식물의 잎 개수와…」가 한 덩어리로 읽힌다.
 * 「제목」이 꼬리표인지 「제목 식물」이라는 말인지 알 수 없다. 실제로 그 지적을 받았다.
 * 그래서 자료 본문은 앱이 파싱해 꼬리표를 따로 그린다.
 *
 * 마크다운 라이브러리를 붙이지 않는다. 필요한 것은 굵게 하나뿐이고,
 * 라이브러리를 넣으면 교재 문장에 든 다른 기호까지 해석해 버린다.
 */

/** **별표 두 개**로 감싼 곳을 굵게 그린다. */
export function withEmphasis(text: string): React.ReactNode[] {
  return text.split(/\*\*(.+?)\*\*/g).map((part, i) =>
    i % 2 === 1 ? (
      <strong key={i} style={{ fontWeight: 700 }}>
        {part}
      </strong>
    ) : (
      <span key={i}>{part}</span>
    ),
  )
}
